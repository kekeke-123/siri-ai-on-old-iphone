#!/usr/bin/env bash
# Generate app/SPKVendor.xcconfig from the artefacts produced by build-ios.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUILD="$ROOT/build/kernel"
RT="$ROOT/third_party/runtime"
OUT="$ROOT/app/SPKVendor.xcconfig"

if [ ! -d "$BUILD" ]; then
    echo "build/kernel missing, run scripts/build-ios.sh first" >&2
    exit 1
fi

{
    echo "// generated by scripts/gen-xcconfig.sh - do not edit by hand"
    echo "HEADER_SEARCH_PATHS = \$(inherited) \\"
    echo "    \"$ROOT/kernel/include\" \\"
    echo "    \"$ROOT/kernel/include/spk\" \\"
    echo "    \"$ROOT/kernel/ios\" \\"
    echo "    \"$RT/include\" \\"
    echo "    \"$RT/ggml/include\" \\"
    echo "    \"$RT/tools/mtmd\""
    echo ""
    echo "OTHER_LDFLAGS = \$(inherited) -lc++ -lz -framework Metal -framework MetalKit \\"
    echo "    -framework Accelerate -framework Foundation -framework UIKit \\"
    echo "    -framework AVFoundation -framework Speech \\"
    echo "    -framework ActivityKit -framework WidgetKit -framework AppIntents"

    while IFS= read -r lib; do
        echo "OTHER_LDFLAGS = \$(inherited) \"$lib\""
    done < <(find "$BUILD" -name '*.a' -not -path '*/CMakeFiles/*' | sort)
} > "$OUT"

echo "== wrote $OUT =="
tail -n +1 "$OUT" | head -30
